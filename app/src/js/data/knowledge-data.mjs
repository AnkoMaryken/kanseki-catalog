let knowledgeLocked = false;
let knowledgeHoverTimer = null;

function initKnowledgePanel() {
  const btn = document.createElement('button');
  btn.id = 'knowledgeBtn';
  btn.className = 'knowledge-btn';
  btn.innerHTML = '<span class="kb-icon">歲</span><span class="kb-text">歲時落款常識</span>';
  btn.setAttribute('aria-label', '打开岁时落款常识面板');
  document.body.appendChild(btn);

  const panel = document.getElementById('knowledgePanel');
  const nav = document.getElementById('knowledgeNav');
  const closeBtn = document.getElementById('knowledgeClose');

  renderKnowledgeContent(0);

  nav.querySelectorAll('.knowledge-nav-item').forEach(item => {
    item.addEventListener('click', function() {
      const cat = parseInt(this.dataset.cat);
      nav.querySelectorAll('.knowledge-nav-item').forEach(n => n.classList.remove('active'));
      this.classList.add('active');
      renderKnowledgeContent(cat);
    });
  });

  function showPanel() { panel.classList.add('show'); btn.classList.add('locked'); }
  function hidePanel() { if (knowledgeLocked) return; panel.classList.remove('show'); btn.classList.remove('locked'); }

  btn.addEventListener('mouseenter', () => { clearTimeout(knowledgeHoverTimer); showPanel(); });
  btn.addEventListener('mouseleave', () => { knowledgeHoverTimer = setTimeout(hidePanel, 300); });
  panel.addEventListener('mouseenter', () => { clearTimeout(knowledgeHoverTimer); });
  panel.addEventListener('mouseleave', () => { knowledgeHoverTimer = setTimeout(hidePanel, 300); });

  btn.addEventListener('click', (e) => {
    e.stopPropagation();
    knowledgeLocked = !knowledgeLocked;
    knowledgeLocked ? showPanel() : hidePanel();
  });

  document.addEventListener('click', (e) => {
    if (knowledgeLocked && !panel.contains(e.target) && e.target !== btn) {
      knowledgeLocked = false; hidePanel();
    }
  });

  if (closeBtn) closeBtn.addEventListener('click', () => { knowledgeLocked = false; hidePanel(); });

  if (window.innerWidth <= 768) {
    btn.addEventListener('click', function toggle() {
      if (!panel.classList.contains('show')) { knowledgeLocked = true; showPanel(); }
    });
  }
}

function renderKnowledgeContent(cat) {
  const content = document.getElementById('knowledgeContent');
  const data = KNOWLEDGE_DATA[cat];
  if (!data) return;
  content.innerHTML = '<h3>' + data.title + '</h3>' + data.html;
}
