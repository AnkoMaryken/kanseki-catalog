def js_literal(obj, indent='  '):
    """把 python 对象转为紧凑 JS 对象字面量 (保持可读性)"""
    lines = [indent + '{']
    for k, v in obj.items():
        if isinstance(v, list):
            inner = ', '.join(
                js_literal(x, '') if isinstance(x, dict) else str(x)
                for x in v
            )
            lines.append(f"{indent}  {k}: [{inner}],")
        elif isinstance(v, str):
            lines.append(f"{indent}  {k}: '{v}',")
        elif isinstance(v, (int, float)):
            lines.append(f"{indent}  {k}: {v},")
    lines.append(indent + '}')
    return '\n'.join(lines)


